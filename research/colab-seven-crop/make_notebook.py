"""Package existing source rows and the auditable trainer into a blank Colab notebook."""
import base64
import hashlib
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
LABELS = ['banana', 'cacao', 'coconut', 'durian', 'mango', 'rice', 'rubber']
FEATURES = ['temperature', 'humidity', 'ph', 'rainfall', 'ndvi', 'elevation', 'slope']
ORIGINAL_FEATURES = ['N', 'P', 'K', 'temperature', 'humidity', 'ph', 'rainfall', 'label']


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def build():
    source = ROOT / 'backend/Crop_recommendation_with_gis.csv'
    original = ROOT / 'backend/Crop_recommendation.csv'
    full, base = pd.read_csv(source), pd.read_csv(original)
    source_hash = sha(source.read_bytes())
    # Exact legacy-feature matches describe row provenance, not confirmed farms.
    original_keys = set(base[ORIGINAL_FEATURES].itertuples(index=False, name=None))
    selected = full.loc[full.label.isin(LABELS)].copy()
    bases = ['matches_original_kaggle_feature_row' if row in original_keys else 'legacy_augmented_profile_row'
             for row in selected[ORIGINAL_FEATURES].itertuples(index=False, name=None)]
    csv = selected[FEATURES + ['label']].copy()
    csv['_record_id'] = [sha(f'{source_hash}:{i}'.encode())[:24] for i in selected.index]
    csv['_source_basis'] = bases
    target = HERE / 'data'; target.mkdir(exist_ok=True)
    data = csv.to_csv(index=False, lineterminator='\n').encode('utf-8')
    (target / 'seven_crop_without_npk.csv').write_bytes(data)
    counts = pd.crosstab(csv.label, csv['_source_basis'])
    manifest = {'schema_version': 1, 'purpose': 'existing_augmented_data_research_comparison_without_npk',
        'dataset_sha256': sha(data), 'feature_order': FEATURES, 'classes': LABELS,
        'source_files': {str(source.relative_to(ROOT)).replace('\\', '/'): sha(source.read_bytes()),
                         str(original.relative_to(ROOT)).replace('\\', '/'): sha(original.read_bytes())},
        'input_rows': len(full), 'selected_rows': len(csv), 'other_crop_rows_excluded': len(full) - len(csv),
        'class_and_provenance_counts': {name: {str(k): int(v) for k, v in row.items()} for name, row in counts.to_dict(orient='index').items()},
        'provenance_labels': {'matches_original_kaggle_feature_row': 'Exact match on the seven original non-GIS columns and target; not verified farm observations. GIS fields remain generated legacy features.',
            'legacy_augmented_profile_row': 'Existing augmented crop-profile row; not a newly observed farm or a new record generated by this notebook.'},
        'features': {name: {'source': 'Existing augmented CSV; unchanged predictor values',
                           'period': 'unresolved legacy source period' if name in ['rainfall', 'temperature', 'humidity'] else 'legacy definition; not independently field verified',
                           'method': 'generated crop-profile GIS proxy' if name in ['ndvi', 'elevation', 'slope'] else 'mixed original rows and generated crop profiles'} for name in FEATURES},
        'npk_included': False, 'rows_generated': 0, 'annualization_performed': False,
        'independent_farm_ids_available': False, 'application_integration_ready': False}
    (target / 'dataset_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    trainer = (HERE / 'train_without_npk.py').read_text(encoding='utf-8')
    requirements = (HERE / 'requirements.txt').read_text(encoding='utf-8').splitlines()
    cells = []

    def cell(kind, text, *, collapsed=False):
        item = {'cell_type': kind, 'id': f'geosustain-{len(cells):02}', 'metadata': {}, 'source': text.splitlines(keepends=True)}
        if kind == 'code':
            item.update(execution_count=None, outputs=[])
            if collapsed: item['metadata'] = {'cellView': 'form', 'jupyter': {'source_hidden': True}}
        cells.append(item)

    cell('markdown', '# GeoSustain: train Decision Tree, SVM and Random Forest\n\n'
         '**Seven crops · NPK excluded · partial research model**\n\n'
         'Run **Runtime → Run all** on a CPU runtime. The starter data and training code are included. '
         'This blank notebook contains no precomputed results. Your run will train all three algorithms and download its outputs.\n\n'
         '**Data basis:** the existing Kaggle-based augmented file, including generated GIS values and crop profiles. '
         'Durian, cacao and rubber are not in the original Kaggle CSV. Scores describe this dataset, not verified farm accuracy. '
         'The labelled climate periods remain unresolved; rainfall is not converted or relabelled as annual. '
         'The app’s annual rainfall/reference checks are separate.\n')
    cell('markdown', '## 1. Prepare the runtime\n\nInstall dependencies before importing the training packages. No API keys or paid GPU are required.\n')
    cell('code', 'import os, sys, subprocess, json, base64\nfrom pathlib import Path\n'
         'try:\n    import google.colab\n    IN_COLAB = True\nexcept ImportError:\n    IN_COLAB = False\n'
         f'DEPENDENCIES = {requirements!r}\n'
         'if IN_COLAB:\n    subprocess.check_call([sys.executable, "-m", "pip", "install", "--quiet", *DEPENDENCIES])\n'
         'PLATFORM = "google_colab" if IN_COLAB else "local"\n'
         'print("Execution platform:", PLATFORM)\nprint("Python:", sys.version)\n')
    cell('markdown', '## 2. Declare the experiment before training\n\nYou may enter your name. Keep the seed, five folds and 500 trees for the supplied reproducible comparison. '
         'No model is promised to win. Selection uses training CV macro F1, before test predictions are read.\n')
    cell('code', 'RESEARCHER_NAME = ""  # Optional: enter your actual name\nSEED = 42\nCV_FOLDS = 5\nFOREST_TREES = 500\n'
         'WORK = Path("/content/geosustain_no_npk") if IN_COLAB else Path("geosustain_no_npk")\nWORK.mkdir(exist_ok=True, parents=True)\n'
         'OUTPUT_PARENT = WORK / "runs"\nprint("NPK will not be used as predictors.")\n')
    cell('markdown', '## 3. Restore the bundled source data and training code\n\n'
         'This cell contains the CSV and auditable Python trainer, rather than precomputed model scores. '
         'The result ZIP includes both for replay. Expand this cell to inspect the source.\n')
    cell('code', f'DATASET_BASE64 = {base64.b64encode(data).decode()!r}\n'
         f'MANIFEST = json.loads({json.dumps(json.dumps(manifest))})\n'
         f'TRAINER_SOURCE = {trainer!r}\n'
         'DATASET_PATH = WORK / "seven_crop_without_npk.csv"\nMANIFEST_PATH = WORK / "dataset_manifest.json"\n'
         'TRAINER_PATH = WORK / "train_without_npk.py"\n'
         'DATASET_PATH.write_bytes(base64.b64decode(DATASET_BASE64))\n'
         'MANIFEST_PATH.write_text(json.dumps(MANIFEST, indent=2), encoding="utf-8")\n'
         'TRAINER_PATH.write_bytes(TRAINER_SOURCE.encode("utf-8"))\n'
         'namespace = {"__name__": "geosustain_colab_trainer", "__file__": str(TRAINER_PATH.resolve())}\n'
         'exec(compile(TRAINER_SOURCE, str(TRAINER_PATH), "exec"), namespace)\n'
         'print("Dataset SHA-256:", namespace["file_hash"](DATASET_PATH))\n', collapsed=True)
    cell('markdown', '## 4. Inspect the dataset\n\nExact duplicate predictor rows are removed **before** splitting. '
         'Missing/nonfinite values, conflicting labels and incomplete crop coverage stop training. '
         'Source identifiers are metadata, never predictors. No independent farm grouping is available in these legacy rows.\n')
    cell('code', 'from IPython.display import display, Image\nimport pandas as pd\n'
         'frame, manifest, audit = namespace["prepare_data"](DATASET_PATH, MANIFEST_PATH)\n'
         'print(json.dumps(audit, indent=2))\ndisplay(pd.DataFrame(manifest["class_and_provenance_counts"]).T)\n'
         'print("Predictors:", namespace["FEATURES"])\ndisplay(frame.head())\n')
    cell('markdown', '## 5. Train and compare the three models\n\n'
         'All models share one 80/20 stratified split and the same five CV folds on training rows. '
         'SVM scaling is fitted inside each fold. After selection by CV, all three are evaluated on the fixed holdout. '
         'Exported models are fitted only on training rows, so their predictions can replay the reported test results.\n')
    cell('code', 'output_dir, results_zip, run = namespace["run_training"](\n'
         '    DATASET_PATH, MANIFEST_PATH, OUTPUT_PARENT, seed=SEED, trees=FOREST_TREES,\n'
         '    cv_folds=CV_FOLDS, execution_platform=PLATFORM, researcher=RESEARCHER_NAME.strip() or "Not supplied",\n)\n'
         'print("Run:", run["run_id"])\nprint("Selected by CV:", run["selection"]["selected_model"])\n'
         'print("Results:", output_dir)\n')
    cell('markdown', '## 6. Inspect your fresh results\n\nMetrics are fractions (0–1) in the CSV; the display below formats them as percentages. '
         'The confusion matrices and per-crop reports come from this run. RF feature importance is global impurity importance, not SHAP or a local explanation.\n')
    cell('code', 'comparison = pd.read_csv(output_dir / "comparison.csv")\n'
         'metric_cols = [c for c in comparison if c.startswith(("cv_", "holdout_"))]\n'
         'display(comparison.style.format({c: "{:.2%}" for c in metric_cols}))\n'
         'display(Image(filename=str(output_dir / "model_comparison.png")))\n'
         'for model in namespace["MODELS"]:\n'
         '    print(model)\n    display(pd.read_csv(output_dir / f"{model}_classification_report.csv", index_col=0))\n'
         '    display(Image(filename=str(output_dir / f"{model}_confusion_matrix.png")))\n'
         'display(Image(filename=str(output_dir / "random_forest_feature_importance.png")))\n')
    cell('markdown', '## 7. Save your training evidence\n\n'
         'Download the ZIP, then save this **executed notebook with its outputs** to your Drive and download its `.ipynb`. '
         'The run record includes versions, timestamps, split assignments and hashes. These records aid replay; they do not independently authenticate where a run occurred. '
         'Your own executed Colab notebook supplies the visible training record.\n')
    cell('code', 'print("Results archive:", results_zip)\n'
         'print("Model input features:", run["features"])\n'
         'print("Application integration ready:", run["application_integration_ready"])\n'
         'if IN_COLAB:\n    from google.colab import files\n    files.download(str(results_zip))\n'
         'else:\n    print("Local QA run; this is not represented as a Colab execution.")\n')
    cell('markdown', '## When NPK arrives\n\n'
         'Keep this run as the **no-NPK baseline**. Check PAGRO units, test methods, soil depth, date/location and '
         'matching crop-labelled observations. Build a new versioned dataset and retrain all three models. '
         'Do not attach unrelated NPK values to existing rows. Adding three predictors changes the model input contract.\n\n'
         '**App integration is separate:** a fresh training run does not automatically replace the installed seven-input experimental model. '
         'The annual-input compatibility and field-validation gaps remain.\n\n'
         'References: [Colab FAQ](https://research.google.com/colaboratory/faq.html), '
         '[scikit-learn leakage guidance](https://scikit-learn.org/1.8/common_pitfalls.html), '
         '[cross-validation](https://scikit-learn.org/1.8/modules/cross_validation.html).\n')
    notebook = {'nbformat': 4, 'nbformat_minor': 5, 'metadata': {
        'colab': {'name': 'GeoSustain_Seven_Crops_No_NPK.ipynb', 'provenance': []},
        'kernelspec': {'display_name': 'Python 3', 'language': 'python', 'name': 'python3'},
        'language_info': {'name': 'python', 'version': '3.11'}}, 'cells': cells}
    path = HERE / 'GeoSustain_Seven_Crops_No_NPK.ipynb'
    path.write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    print(json.dumps({'notebook': str(path.relative_to(ROOT)), 'rows': len(csv),
                      'classes': LABELS, 'source_counts': manifest['class_and_provenance_counts']}, indent=2))
    return path


if __name__ == '__main__':
    build()
