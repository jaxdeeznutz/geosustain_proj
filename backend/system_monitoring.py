"""Small, read-only checks for the administrator, never invented uptime metrics."""
from datetime import datetime, timezone
from time import monotonic
import database


def snapshot():
    checks = [dict(key='api', label='API services', status='healthy',
                   message='The authenticated monitoring request reached the backend.')]
    connection = None
    started = monotonic()
    database_ok = False
    try:
        connection = database.get_conn()
        with connection.cursor() as cur:
            cur.execute("SET LOCAL statement_timeout = '2000ms'")
            cur.execute('SELECT 1')
            cur.fetchone()
            database_ok = True
            checks.append(dict(key='database', label='Database', status='healthy',
                               message='Connection and read query succeeded.',
                               latency_ms=round((monotonic()-started)*1000)))
            try:
                cur.execute('SELECT id FROM reports LIMIT 1')
                cur.fetchone()
                checks.append(dict(key='reports', label='Report records', status='healthy',
                                   message='Saved report records are readable. PDFs are generated by the app; no file bucket is monitored.'))
            except Exception:
                checks.append(dict(key='reports', label='Report records', status='unavailable',
                                   message='Report records could not be read. Check database migrations and access.'))
    except Exception:
        checks.append(dict(key='database', label='Database', status='unavailable',
                           message='The database connection or read query failed. Check the deployment logs.'))
        checks.append(dict(key='reports', label='Report records', status='unavailable',
                           message='Report access could not be checked without the database.'))
    finally:
        if connection is not None:
            connection.close()
    try:
        from rainfallDatasets import model_health
        loaded = model_health().get('status') == 'loaded'
    except Exception:
        loaded = False
    checks.append(dict(key='ai', label='Crop ranking engine',
                       status='healthy' if loaded else 'unavailable',
                       message='Installed AI artifact loaded.' if loaded else 'The installed AI artifact is unavailable.'))
    checks.append(dict(key='maps', label='Maps & imagery', status='client_side',
                       message='Rendered in the browser. This server check cannot verify map tiles or the browser API key.'))
    return dict(checked_at=datetime.now(timezone.utc).isoformat(),
                status='healthy' if database_ok and all(c['status'] != 'unavailable' for c in checks) else 'attention',
                checks=checks, basis='Point-in-time checks; not continuous uptime monitoring.')
